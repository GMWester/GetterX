#!/usr/bin/env python3
"""Regenerates packages/getterx_core/lib/mozilla_roots.dart from the latest
certifi wheel (Mozilla's CA bundle). Run: python3 tool/update_roots.py"""
import glob, io, json, re, tempfile, urllib.request, zipfile

meta = json.load(urllib.request.urlopen("https://pypi.org/pypi/certifi/json", timeout=60))
version = meta["info"]["version"]
wheel = next(u for u in meta["urls"] if u["filename"].endswith(".whl"))
data = urllib.request.urlopen(wheel["url"], timeout=60).read()
import hashlib
assert hashlib.sha256(data).hexdigest() == wheel["digests"]["sha256"], "certifi wheel checksum mismatch"
pem = zipfile.ZipFile(io.BytesIO(data)).read("certifi/cacert.pem").decode()
blocks = re.findall(r"-----BEGIN CERTIFICATE-----\n.*?\n-----END CERTIFICATE-----", pem, re.S)
out = (
    f"// GENERATED by tool/update_roots.py from certifi (Mozilla's CA bundle) {version}. Do not edit.\n"
    f"// {len(blocks)} trusted root certificates, used when the operating system's store lacks a root.\n"
    "// ignore_for_file: lines_longer_than_80_chars\n\n"
    "const mozillaRootsPem = r'''\n" + "\n".join(blocks) + "\n''';\n"
)
open("packages/getterx_core/lib/mozilla_roots.dart", "w").write(out)
print(f"certifi {version}: {len(blocks)} roots")
